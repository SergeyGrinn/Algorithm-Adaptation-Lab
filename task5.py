arr = [7, 3, 5, 3, 1, 7]
def selection_sort_with_duplicates(arr):
    n = len(arr)
    for i in range(n):
        min_index = i
        for j in range(i + 1, n):
            if arr[j] < arr[min_index]:
                min_index = j
        arr[i], arr[min_index] = arr[min_index], arr[i]
    return arr

print(selection_sort_with_duplicates(arr))